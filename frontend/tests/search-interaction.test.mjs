import test from 'node:test';
import assert from 'node:assert/strict';
import {mountApp} from './dom-harness.mjs';
const openSearch=()=>{const ui=mountApp();ui.document.getElementById('skip').click();return ui;};
test('Apply combined filters, then remove individual conditions without clearing the rest',()=>{
 const ui=openSearch(),d=ui.document;
 d.getElementById('search-region').value='Chuncheon';
 d.getElementById('facility-type').value='hospital';
 d.getElementById('department').value='internal';
 d.getElementById('open-only').checked=true;
 d.getElementById('search-form').emit('submit');
 assert.equal(d.querySelectorAll('[data-remove-filter]').length,4);
 assert.equal(d.querySelectorAll('.facility-card').length,1);
 d.querySelectorAll('[data-remove-filter]').find(n=>n.dataset.removeFilter==='openOnly').click();
 assert.equal(d.querySelectorAll('.facility-card').length,2);
 assert.equal(d.getElementById('department').value,'internal');
 assert.equal(d.getElementById('facility-type').value,'hospital');
 assert.equal(d.getElementById('search-region').value,'Chuncheon');
 d.querySelectorAll('[data-remove-filter]').find(n=>n.dataset.removeFilter==='type').click();
 assert.equal(d.getElementById('facility-type').value,'all');
 assert.equal(d.getElementById('department').value,'internal');
});
test('Select on map, switch facility, and return to the original list scroll position',()=>{
 const ui=openSearch(),d=ui.document;
 d.querySelector('.facility-results').scrollTop=177;
 d.querySelectorAll('[data-facility]').find(n=>n.dataset.facility==='sample-a').click();
 assert.ok(d.getElementById('detail-heading'));
 assert.equal(d.querySelectorAll('.map-pin').find(n=>n.dataset.facility==='sample-a').attributes['aria-pressed'],'true');
 assert.equal(d.querySelector('.facility-results').scrollTop,0);
 d.querySelector('.facility-results').scrollTop=30;
 d.querySelectorAll('[data-facility]').find(n=>n.dataset.facility==='sample-b').click();
 d.getElementById('close-detail').click();
 assert.equal(d.querySelectorAll('.facility-card').length,6);
 assert.equal(d.querySelector('.facility-results').scrollTop,177);
});
test('Pending filters and unsent chat survive language and display changes',()=>{
 const ui=openSearch(),d=ui.document;
 d.getElementById('chat-open')?.click();
 d.getElementById('composer-input').value='작성 중인 메시지';
 d.getElementById('search-region').value='Chuncheon';
 d.getElementById('facility-type').value='pharmacy';
 d.getElementById('language').click();
 assert.equal(d.getElementById('facility-type').value,'pharmacy');
 assert.equal(d.getElementById('composer-input').value,'작성 중인 메시지');
 d.getElementById('display-list').click();
 assert.equal(d.getElementById('search-region').value,'Chuncheon');
 assert.equal(d.getElementById('composer-input').value,'작성 중인 메시지');
 d.getElementById('search-form').emit('submit');
 assert.equal(d.querySelectorAll('.facility-card').length,2);
});
test('Empty results recover after reset and report remains reachable from the search header',()=>{
 const ui=openSearch(),d=ui.document;
 d.getElementById('search-region').value='nothing-matches';
 d.getElementById('search-form').emit('submit');
 assert.equal(d.querySelectorAll('.facility-card').length,0);
 assert.ok(d.querySelector('.results-empty'));
 d.querySelectorAll('[data-reset]')[0].click();
 assert.equal(d.querySelectorAll('.facility-card').length,6);
 d.querySelectorAll('button[data-view]').find(n=>n.dataset.view==='report').click();
 assert.equal(d.body.dataset.view,'report');
});
