// 개인정보 패턴 가리기(정규식, 결정적).
// 순서: 이메일 → 카드번호(16자리) → 주민등록번호(13자리) → 전화번호.
// 긴 숫자 패턴을 먼저 가려야 짧은 패턴이 일부만 잡지 않는다.
// 나이("32살", "만 40세"), 약 용량("500mg"), 날짜("3일 전", "2026-11-15")는 가리지 않는다.

const SEP = '[-.\\s]?';

const PATTERNS = [
  ['email', /[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}/g, '[이메일]'],
  // 4-4-4-4 (하이픈·공백·점 또는 붙여 씀; 구분자는 같은 것으로)
  ['card', /(?<!\d)\d{4}([-.\s]?)\d{4}\1\d{4}\1\d{4}(?!\d)/g, '[카드번호]'],
  // 6-7, 뒷자리 첫 숫자 1~8 (붙여 쓴 13자리 포함)
  //   구분자(하이픈·공백)가 있으면 날짜 검사 없이, 붙여 쓴 13자리는 앞 6자리가 날짜 모양일 때만
  ['rrn', /(?<!\d)\d{6}(?:\s?-\s?|\s)[1-8]\d{6}(?!\d)|(?<!\d)\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])[1-8]\d{6}(?!\d)/g, '[주민번호]'],
  ['phone', new RegExp([
    // 휴대폰: 010-1234-5678, 010 1234 5678, 010.1234.5678, 01012345678, +82 10-1234-5678
    `(?:(?<!\\d)\\+82${SEP}0?|(?<!\\d)0)1[016789]${SEP}\\d{3,4}${SEP}\\d{4}(?!\\d)`,
    // 일반 전화: 02-123-4567, 031-123-4567, 070-1234-5678 (+82 2-…)
    `(?:(?<!\\d)\\+82${SEP}|(?<!\\d)0)(?:2|[3-6][1-5]|70)${SEP}\\d{3,4}${SEP}\\d{4}(?!\\d)`,
    // 대표번호: 1588-1234 (구분자 필수)
    `(?<!\\d)1[5-9]\\d{2}[-.]\\d{4}(?!\\d)`,
  ].join('|'), 'g'), '[전화번호]'],
];

/**
 * @param {string} s
 * @returns {{text:string, masked:{phone:number,email:number,rrn:number,card:number}}}
 */
export function maskPii(s) {
  let text = String(s ?? '');
  const masked = {phone: 0, email: 0, rrn: 0, card: 0};
  for (const [kind, re, replacement] of PATTERNS) {
    text = text.replace(re, () => { masked[kind] += 1; return replacement; });
  }
  return {text, masked};
}
